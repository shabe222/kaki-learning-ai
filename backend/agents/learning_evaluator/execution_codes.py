def project_issue_to_public(code: EvaluationIssueCode) -> PublicEvaluationIssueCode:
    if type(code) is not EvaluationIssueCode:
        return PublicEvaluationIssueCode.EVALUATION_EXECUTION_FAILED
    return ISSUE_TO_PUBLIC[code]

def assert_mapping_completeness() -> None:
    assert set(TERMINAL_CODES_BY_STATE) == set(ReservationLifecycleState)
    assert set().union(*TERMINAL_CODES_BY_STATE.values()) == set(ReservationTerminalCode)
    assert set(RESERVATION_TO_ISSUE) == set(ReservationConflictCode)
    assert set(COMMIT_TO_ISSUE) == set(CommitConflictCode)
    assert set(ABORT_TO_TERMINAL) == set(AbortReasonCode)
    assert set(COMMIT_REJECTION_TO_TERMINAL) == {
        CommitConflictCode.INVALID_RESERVATION_STATE,
        CommitConflictCode.RESERVATION_RESULT_BINDING_MISMATCH,
        CommitConflictCode.RESULT_REF_MISMATCH,
        CommitConflictCode.RESULT_DIGEST_MISMATCH,
        CommitConflictCode.RESULT_REVISION_MISMATCH,
        CommitConflictCode.EVALUATION_REVISION_CONFLICT,
    }
    assert set(ISSUE_TO_PUBLIC) == set(EvaluationIssueCode)
    assert set(FIXED_ISSUE_MESSAGES) == set(EvaluationIssueCode)
    assert set(PUBLIC_ISSUE_MESSAGES) == set(PublicEvaluationIssueCode)

assert_mapping_completeness()
